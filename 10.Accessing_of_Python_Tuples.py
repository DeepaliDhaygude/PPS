#Accessing of Python Tuples 

# Accessing Tuple with Indexing
tup = tuple("Python")
print(tup[0])

# Accessing a range of elements using slicing
print(tup[1:4])  
print(tup[:3])

# Tuple unpacking
tup = ("Python", "Programming", "Language")

# This line unpack values of Tuple1
a, b, c = tup
print(a)
print(b)
print(c)
